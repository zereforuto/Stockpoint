/**
 * Self-contained HTML used for PDF report exports. Charts are embedded as raw
 * <svg> markup captured from the on-screen Recharts instances.
 */

import { escapeHtml } from './html'

export interface ReportLine {
  label: string
  value: string
  strong?: boolean
}

export interface ReportSection {
  title: string
  columns?: string[]
  rows?: string[][]
  lines?: ReportLine[]
}

export interface ReportDocument {
  title: string
  subtitle?: string
  shopName: string
  address: string
  currencySymbol: string
  /** Raw <svg>...</svg> markup from the renderer charts. */
  charts?: string[]
  sections: ReportSection[]
  footer?: string
}

function renderSection(section: ReportSection): string {
  const lines = (section.lines ?? [])
    .map(
      (line) => `<div class="kv${line.strong ? ' strong' : ''}"><span>${escapeHtml(
        line.label
      )}</span><span>${escapeHtml(line.value)}</span></div>`
    )
    .join('')

  const table =
    section.columns && section.rows
      ? `<table>
          <thead><tr>${section.columns.map((c) => `<th>${escapeHtml(c)}</th>`).join('')}</tr></thead>
          <tbody>
            ${section.rows
              .map(
                (row) =>
                  `<tr>${row
                    .map((cell, index) =>
                      index === 0 ? `<td class="left">${escapeHtml(cell)}</td>` : `<td>${escapeHtml(cell)}</td>`
                    )
                    .join('')}</tr>`
              )
              .join('')}
          </tbody>
        </table>`
      : ''

  return `<section>
    <h2>${escapeHtml(section.title)}</h2>
    ${lines}
    ${table}
  </section>`
}

export function buildReportHtml(doc: ReportDocument): string {
  const charts = (doc.charts ?? [])
    .filter((svg) => svg.includes('<svg'))
    .map((svg) => `<div class="chart">${svg}</div>`)
    .join('')

  return `<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<title>${escapeHtml(doc.title)}</title>
<style>
  * { box-sizing: border-box; }
  body {
    margin: 0;
    padding: 24px;
    color: #111;
    font-family: "Segoe UI", system-ui, -apple-system, sans-serif;
    font-size: 12px;
  }
  h1 { font-size: 20px; margin: 0; }
  h2 { font-size: 14px; margin: 18px 0 8px; border-bottom: 1px solid #ccc; padding-bottom: 4px; }
  .head { display: flex; justify-content: space-between; align-items: flex-end; border-bottom: 2px solid #111; padding-bottom: 8px; }
  .muted { color: #555; }
  .kv { display: flex; justify-content: space-between; padding: 3px 0; border-bottom: 1px dotted #ddd; }
  .kv.strong { font-weight: 700; font-size: 13px; }
  table { width: 100%; border-collapse: collapse; margin-top: 6px; }
  th, td { padding: 5px 6px; border-bottom: 1px solid #e2e2e2; }
  th { text-align: right; background: #f4f4f4; font-weight: 600; }
  th:first-child, td.left { text-align: left; }
  td { text-align: right; }
  .chart { margin: 12px 0; page-break-inside: avoid; }
  .chart svg { width: 100%; height: auto; }
  .footer { margin-top: 24px; padding-top: 8px; border-top: 1px solid #ccc; color: #777; font-size: 10px; }
  @media print { body { padding: 0; } }
</style>
</head>
<body>
  <div class="head">
    <div>
      <h1>${escapeHtml(doc.title)}</h1>
      <div class="muted">${escapeHtml(doc.shopName)}${doc.address ? ` &middot; ${escapeHtml(doc.address)}` : ''}</div>
    </div>
    <div class="muted">${escapeHtml(doc.subtitle ?? '')}</div>
  </div>
  ${charts}
  ${doc.sections.map(renderSection).join('\n')}
  <div class="footer">${escapeHtml(doc.footer ?? `Generated by StockPoint &middot; ${doc.currencySymbol}`)}</div>
</body>
</html>`
}
